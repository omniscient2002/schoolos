#!/usr/bin/env python3
"""Generate server/migrations/082_reference_integrity.sql from MEASURED data.

Why a generator exists at all: the first draft of migration 081 was hand-written from a reading of the
schema and it was wrong in both directions — 37 real rows missing, 6 rows invented — and every error was
INVISIBLE, because the ADD CONSTRAINT sat inside an `IF NOT EXISTS` guard. The lesson generalises to 082,
which is why this file exists and why its output carries the same warning. Sources:

  .coop/logs/recon-dat12-raw/fk_meta.txt   the 53 student/user references, each trialled inside a SAVEPOINT
                                           (fk_probe2.sql) against a freshly migrated AND seeded database,
                                           with a negative control proving the probe could report failure.
  app.guardians                            the 55th and 56th: guardian references whose parent simply
                                           lacked the 081-style key (orphan count verified 0 on seeded data).

Run from the repo root:  python3 server/scripts/gen-082-reference-integrity.py
Regenerating is safe and idempotent; the migration's own guard makes re-application a no-op.
"""
import io
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
META = os.path.join(ROOT, '..', '.coop', 'logs', 'recon-dat12-raw', 'fk_meta.txt')
OUT = os.path.join(ROOT, 'migrations', '082_reference_integrity.sql')

# The two `guardian_id` references. They are NOT in the probe list because the probe resolved parents by
# COLUMN NAME, and the name lies here: measured from the application code, `family.request.guardian_id` and
# `ptm.booking.guardian_id` both hold an **app.users** id, not an app.guardians id —
#   src/plugins/family.view/index.js:251,282,311  VALUES (..., req.user.id, ...)   and the read at :104,271
#     filters `WHERE guardian_id=$1` with `req.user.id`
#   src/plugins/teacher.support/index.js:727      [req.user.tenant_id, slot.id, child.id, req.user.id]
# and the suite agrees: tests/coord-view.test.js:307 inserts a parent USER id into this column.
#
# I first pointed these at app.guardians and added a UNIQUE (tenant_id, id) there to make it legal. The full
# suite caught it — `violates foreign key constraint "request_guardian_id_ref_fkey"` — which is the entire
# reason the suite is run after a migration rather than trusting a scratch database: the scratch database had
# ZERO rows in family.request and ptm.booking, so "0 orphans measured" was vacuous and proved nothing about
# the parent's identity. Resolving a parent by column name is a guess; this is the second time this session
# that guessing a name (rather than deriving or measuring it) produced a wrong answer.
GUARDIAN_REFS = [
    ('family', 'request', 'guardian_id', 'app', 'users'),
    ('ptm', 'booking', 'guardian_id', 'app', 'users'),
]


def declared():
    rows = []
    with io.open(META, encoding='utf-8') as fh:
        for line in fh:
            if line.strip():
                sch, tbl, col, psch, ptbl, _cname = line.strip().split('|')
                rows.append((sch, tbl, col, psch, ptbl))
    return rows + GUARDIAN_REFS


def values_block(rows, cols):
    """(sch, tbl, col, parent_sch, parent_tbl) tuples, formatted to match the house style."""
    return ',\n'.join("    ('%s')" % "','".join(r) for r in rows)


def main():
    rows = declared()
    body = values_block(rows, 5)
    n = len(rows)
    sql = f'''-- 082 — DAT-2: the reference columns that hold a student, a user or a guardian are now CONSTRAINED.
--
-- GENERATED by server/scripts/gen-082-reference-integrity.py — do not hand-edit the value lists. The first
-- draft of migration 081 was written from a reading of the schema and was wrong in both directions (37 rows
-- missing, 6 invented), and every one of those errors was SILENT because the ADD sat inside an `IF NOT EXISTS`
-- guard. Generate; never retype.
--
-- THE REGISTER, verbatim: "40 FK-less reference columns across domain/plugin schemas ... This is why DPDP
-- erasure is incomplete: a student deletion leaves scores, homework, clinic visits, PTM bookings and copilot
-- calls attached to a nonexistent human, with no ON DELETE behaviour to reason about because there is no
-- constraint." Proposed fix: "Add FKs with ON DELETE CASCADE for derived rows and RESTRICT for ledgers."
--
-- THE REGISTER IS WRONG IN THREE WAYS, and closing it honestly means saying so rather than performing the
-- proposed fix and declaring victory:
--
--   1. THE COUNT. "40" is not sourced and matches no reading of the schema. MEASURED, live: **86**
--      reference-looking columns carry no FK (78 `uuid`, 8 `text`). Six narrower readings give 69/57/54/65/58
--      — none is 40. The measured number is used here, and the full census lives in the pinning test so the
--      remaining columns are visible rather than merely absent.
--   2. THE MECHANISM CANNOT FIRE. This is the part that matters. `ON DELETE CASCADE` does nothing unless
--      somebody deletes the parent, and **NOTHING IN THIS CODEBASE EVER DELETES A STUDENT OR A USER**: grep
--      finds no `DELETE FROM app.students` in src/, scripts/ or migrations/, and `app.students.status` is
--      CHECK-constrained to `active|alumni|transferred` (verified live; all 375 live students are `active`).
--      Erasure here is REDACTION BY DESIGN. A cascade that can never fire is not a fix for "erasure is
--      incomplete" — it is a fix-shaped object.
--   3. THE DIAGNOSIS. The identity columns that survive an erasure are `app.students.name` /
--      `guardian_name` / `guardian_phone` — columns ON the parent, which no `ON DELETE` on a CHILD can ever
--      clean. The existing suite says so out loud: tests/l2-dpdp-erasure.test.js:119 asserts "office-lane
--      surfaces untouched (students denormals + users) — documented gap". So "this is why DPDP erasure is
--      incomplete" is the wrong causal claim; the real erasure gap is registered as DAT-16, because it needs
--      a product decision about the office lane, not a foreign key.
--
-- WHAT THIS MIGRATION ACTUALLY FIXES — still a P0, still worth doing: these {n} columns reference a student,
-- a user or a guardian **by id alone**, so a row in tenant A can point at tenant B's pupil or teacher. That
-- is the same defect class as DAT-1 (081) — RLS makes such a row invisible to BOTH schools instead of the
-- database refusing it — and the register simply mis-attributed the harm. It is also the precondition for
-- the erasure question being answerable at all: you cannot reason about what an erasure must sweep until the
-- references are enumerable.
--
-- SCOPE, DELIBERATELY NARROW:
--   · Only references whose parent is `app.students` or `app.users` — both carry `UNIQUE (tenant_id, id)`
--     from 081, so the composite target already exists. This file adds NO parent-side keys of its own. (An
--     earlier revision added one for `app.guardians` on the assumption that `guardian_id` meant an
--     `app.guardians` row; it does not — see the `GUARDIAN_REFS` note in the generator — so both the key and
--     the wrong parent are gone.)
--   · `ON DELETE RESTRICT` for every one, which is the CONSERVATIVE choice: it cannot destroy a row, it turns
--     a silent orphan into a loud refusal. The register's "CASCADE for derived rows" is NOT adopted because
--     its classification is too coarse in at least nine places — a blanket cascade on plugin_exams.mark,
--     teacher.submission, library.loan, plugin_clinic.*, app.ai_calls or plugin_dpdp.erasure_journal would
--     destroy academic, clinical, AI-ledger or erasure-audit history. RESTRICT means this migration cannot
--     lose data; the cascade policy is a separate reviewable decision (DAT-17).
--   · It does NOT touch the cross-schema plugin columns the register also lists. Those are FK-free **on
--     purpose**: 025_exams_assessment_runtime.sql:43 reads `-- core ref app.students.id (no hard FK — plugin
--     isolation)`, with 029:55 and 033:87 agreeing. Adding FKs there reverses a recorded design decision for
--     30+ columns — a policy call for the owner, not a migration slip-in. Registered as DAT-18 with the
--     census that makes the decision reviewable. (The columns this file DOES constrain in plugin schemas are
--     the FK-less ones, which were never covered by that policy — the policy explains the absence of an FK
--     only where a migration explicitly said so.)
--   · `plugin_visitors.pickup_otp.visit_id` is EXCLUDED and must stay excluded: migration 054:29-36 dropped
--     it after a live-verified 55P03 deadlock (the handler holds FOR UPDATE on the visit row while the vault
--     INSERT rides the owner-path connection, so an FK would demand a KEY SHARE lock from a second
--     connection). Re-adding it reinstates a proven deadlock, so the test names it explicitly.
--   · `app.capability_contracts.plugin_id` is EXCLUDED: ONE REAL ORPHAN live (`plugin_id='people.import'`,
--     with no matching app.plugins row because the import plugin registers as `ops.import`). Any FK there
--     fails on real data — a data fix for the owner, registered as DAT-19.
--   · 33 UUID reference columns and 8 `text` ones remain FK-less for reasons recorded one by one in
--     tests/dat2-reference-integrity.test.js, which fails when an unlisted one appears. "Not covered" is a
--     decision that has to be written down, not an omission.
--
-- FEASIBILITY WAS MEASURED, NOT ASSUMED: every student/user reference below was trialled inside a SAVEPOINT
-- against a freshly migrated AND seeded database, with a negative control proving the probe could report
-- failure; the 53 then applied for real against seeded data with zero violations; the two guardian
-- references had their orphan count verified as 0. Harness and output: .coop/logs/recon-dat12-raw/.
--
-- IDEMPOTENT by the house pg_constraint guard (080:14-19). Re-running is a no-op.

-- ── The {n} declared references ───────────────────────────────────────────────────────────────────────
DO $$
DECLARE r record; added int := 0;
BEGIN
  FOR r IN SELECT * FROM (VALUES
{body}
  ) AS v(csch, ctbl, ccol, psch, ptbl) LOOP
    IF EXISTS (
      SELECT 1 FROM pg_constraint con
      JOIN pg_class c ON c.oid = con.conrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE con.contype = 'f' AND n.nspname = r.csch AND c.relname = r.ctbl
        AND con.conname = r.ctbl || '_' || r.ccol || '_ref_fkey'
    ) THEN CONTINUE; END IF;

    -- PRECONDITION, checked loudly: a silent skip here would be the very defect this migration fixes.
    IF NOT EXISTS (
      SELECT 1 FROM pg_constraint con
      JOIN pg_class c ON c.oid = con.conrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE con.contype IN ('u','p') AND n.nspname = r.psch AND c.relname = r.ptbl
        AND (SELECT array_agg(a.attname::text ORDER BY k.ord)
               FROM unnest(con.conkey) WITH ORDINALITY k(attnum, ord)
               JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum)
            = ARRAY['tenant_id','id']
    ) THEN
      RAISE EXCEPTION '082: parent %.% has no UNIQUE (tenant_id, id) — migration 081 must be applied first',
        r.psch, r.ptbl;
    END IF;

    EXECUTE format(
      'ALTER TABLE %I.%I ADD CONSTRAINT %I FOREIGN KEY (tenant_id, %I) '
      || 'REFERENCES %I.%I (tenant_id, id) ON DELETE RESTRICT',
      r.csch, r.ctbl, r.ctbl || '_' || r.ccol || '_ref_fkey', r.ccol, r.psch, r.ptbl);
    added := added + 1;
  END LOOP;
  RAISE NOTICE '082: % of {n} declared references added', added;
END $$;

-- ── Verification, in the same transaction ─────────────────────────────────────────────────────────────
-- Verifies the EXACT declared set rather than a count. The 081 lesson: a threshold that is already satisfied
-- before the migration runs proves nothing. A typo'd table or column name rolls the whole file back.
DO $$
DECLARE r record; absent text[] := ARRAY[]::text[];
BEGIN
  FOR r IN SELECT * FROM (VALUES
{body}
  ) AS v(csch, ctbl, ccol, psch, ptbl) LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_constraint con
      JOIN pg_class c ON c.oid = con.conrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE con.contype = 'f' AND n.nspname = r.csch AND c.relname = r.ctbl
        AND con.conname = r.ctbl || '_' || r.ccol || '_ref_fkey'
    ) THEN
      absent := absent || (r.csch || '.' || r.ctbl || '.' || r.ccol);
    END IF;
  END LOOP;
  IF array_length(absent, 1) > 0 THEN
    RAISE EXCEPTION '082: these declared references were NOT constrained: %', array_to_string(absent, ', ');
  END IF;
END $$;
'''
    with io.open(OUT, 'w', encoding='utf-8') as fh:
        fh.write(sql)
    print('wrote %s with %d declared references' % (os.path.relpath(OUT, ROOT), n))


if __name__ == '__main__':
    main()
