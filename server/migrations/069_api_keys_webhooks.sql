-- 065 · scoped API keys + outbound webhooks (L2-4.1, Wave 4 — claimed by L2, blocks.md).
-- API keys: machine identities for read-only integrations. The RAW key is shown
-- once at creation; only sha256(key) is stored. Scopes gate read doors
-- (default-deny; the kernel hook resolves req.apiScopes). 'api' role is NOT in
-- app.users.role CHECK — these are NOT user rows; the auth path synthesizes a
-- principal from the key row.
CREATE TABLE IF NOT EXISTS app.api_keys (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id    uuid NOT NULL,
  key_hash     text NOT NULL UNIQUE,        -- sha256 hex of the raw key
  name         text NOT NULL,
  scopes       text[] NOT NULL DEFAULT '{}',
  revoked_at   timestamptz,
  last_used_at timestamptz,
  created_by   uuid REFERENCES app.users(id),
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS api_keys_tenant_idx ON app.api_keys (tenant_id) WHERE revoked_at IS NULL;

-- Outbound webhooks: per-tenant subscriptions; deliveries mirror the outbox
-- retry semantics (attempts/backoff/parked-failed). The signing secret is
-- generated by the kernel at subscription time (shown once, stored server-side —
-- it is OUR signature key, not a held third-party credential).
CREATE TABLE IF NOT EXISTS app.webhook_subscriptions (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id  uuid NOT NULL,
  url        text NOT NULL,
  events     text[] NOT NULL DEFAULT '{}',  -- app.events.topic match list ('*' = all)
  sign_secret text NOT NULL,
  active     boolean NOT NULL DEFAULT true,
  created_by uuid REFERENCES app.users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS webhook_subs_active_idx ON app.webhook_subscriptions (tenant_id) WHERE active;

CREATE TABLE IF NOT EXISTS app.webhook_deliveries (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id       uuid NOT NULL,
  subscription_id uuid NOT NULL REFERENCES app.webhook_subscriptions(id),
  event_id        uuid NOT NULL,
  topic           text NOT NULL,
  payload         jsonb NOT NULL DEFAULT '{}'::jsonb,
  status          text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued','delivered','failed')),
  attempts        int NOT NULL DEFAULT 1,
  last_error      text,
  response_code   int,
  next_attempt_at timestamptz,
  delivered_at    timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (subscription_id, event_id)        -- at-least-once per (sub, event)
);
CREATE INDEX IF NOT EXISTS webhook_deliveries_due_idx
  ON app.webhook_deliveries (next_attempt_at) WHERE status = 'queued';

ALTER TABLE app.api_keys ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.api_keys FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS api_keys_tenant ON app.api_keys;
CREATE POLICY api_keys_tenant ON app.api_keys
  USING (tenant_id = current_setting('schoolos.tenant_id', true)::uuid);

ALTER TABLE app.webhook_subscriptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.webhook_subscriptions FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS webhook_subs_tenant ON app.webhook_subscriptions;
CREATE POLICY webhook_subs_tenant ON app.webhook_subscriptions
  USING (tenant_id = current_setting('schoolos.tenant_id', true)::uuid);

ALTER TABLE app.webhook_deliveries ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.webhook_deliveries FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS webhook_deliveries_tenant ON app.webhook_deliveries;
CREATE POLICY webhook_deliveries_tenant ON app.webhook_deliveries
  USING (tenant_id = current_setting('schoolos.tenant_id', true)::uuid);

-- management is owner-path; the app role never touches key/subscription rows
REVOKE ALL ON app.api_keys, app.webhook_subscriptions, app.webhook_deliveries FROM schoolos_app;
